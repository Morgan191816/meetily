"use client";
import { useState, useEffect, useRef } from 'react';
import { motion } from 'framer-motion';
import { MeetingSummary, SummaryProcessResponse } from '@/types';
import { useSidebar } from '@/components/Sidebar/SidebarProvider';
import Analytics from '@/lib/analytics';
import { invoke } from '@tauri-apps/api/core';
import { toast } from 'sonner';
import { TranscriptPanel } from '@/components/MeetingDetails/TranscriptPanel';
import { MinutesPanel } from '@/components/MeetingDetails/MinutesPanel';
import { QualityPanel } from '@/components/MeetingDetails/QualityPanel';
import { MeetingDetailsSplitView, type MeetingDetailsTab } from '@/components/MeetingDetails/MeetingDetailsSplitView';
import { ModelConfig } from '@/components/ModelSettingsModal';
import { parseSummaryContent } from '@/lib/summary-content';

// Custom hooks
import { useMeetingData } from '@/hooks/meeting-details/useMeetingData';
import { useMinutesGeneration } from '@/hooks/useMinutesGeneration';
import { useCopyOperations } from '@/hooks/meeting-details/useCopyOperations';
import { useMeetingOperations } from '@/hooks/meeting-details/useMeetingOperations';

export default function PageContent({
  meeting,
  summaryData,
  shouldAutoGenerate,
  onAutoGenerateComplete,
  onMeetingUpdated,
  onRefetchTranscripts,
  // Pagination props for efficient transcript loading
  segments,
  hasMore,
  isLoadingMore,
  totalCount,
  loadedCount,
  onLoadMore,
}: {
  meeting: any;
  summaryData: MeetingSummary | null;
  initialSummary: SummaryProcessResponse | null;
  shouldAutoGenerate?: boolean;
  onAutoGenerateComplete?: () => void;
  onMeetingUpdated?: () => Promise<void>;
  onRefetchTranscripts?: () => Promise<void>;
  // Pagination props
  segments?: any[];
  hasMore?: boolean;
  isLoadingMore?: boolean;
  totalCount?: number;
  loadedCount?: number;
  onLoadMore?: () => void;
}) {
  console.log('📄 PAGE CONTENT: Initializing with data:', {
    meetingId: meeting.id,
    summaryDataKeys: summaryData ? Object.keys(summaryData) : null,
    transcriptsCount: meeting.transcripts?.length
  });

  // State
  const [customPrompt, setCustomPrompt] = useState<string>('');
  const isRecording = false;
  const [activeTab, setActiveTab] = useState<MeetingDetailsTab>('transcript');

  const autoSwitchedSummaryMeetingIdsRef = useRef(new Set<string>());
  const manuallySelectedTabMeetingIdsRef = useRef(new Set<string>());
  const autoGeneratedMeetingIdsRef = useRef(new Set<string>());

  // Sidebar context
  const { serverAddress } = useSidebar();

  // Custom hooks
  const meetingData = useMeetingData({ meeting, summaryData, onMeetingUpdated });

  // Save model config to backend database and sync via event
  const handleSaveModelConfig = async (config?: ModelConfig) => {
    if (!config) return;
    try {
      await invoke('api_save_model_config', {
        provider: config.provider,
        model: config.model,
        whisperModel: config.whisperModel,
        apiKey: config.apiKey ?? null,
        ollamaEndpoint: config.ollamaEndpoint ?? null,
      });

      // Emit event so ConfigContext and other listeners stay in sync
      const { emit } = await import('@tauri-apps/api/event');
      await emit('model-config-updated', config);

      toast.success('模型设置已保存');
    } catch (error) {
      console.error('Failed to save model config:', error);
      toast.error('保存模型设置失败');
    }
  };

  const minutesGeneration = useMinutesGeneration(meeting.id);
  const { minutes, status: minutesStatus, loaded: minutesLoaded, generate: generateMinutes } = minutesGeneration;

  const copyOperations = useCopyOperations({
    meeting,
    transcripts: meetingData.transcripts,
    meetingTitle: meetingData.meetingTitle,
    aiSummary: meetingData.aiSummary,
    blockNoteSummaryRef: meetingData.blockNoteSummaryRef,
  });

  const meetingOperations = useMeetingOperations({
    meeting,
  });

  // Track page view
  useEffect(() => {
    Analytics.trackPageView('meeting_details');
  }, []);

  useEffect(() => {
    const hasSummary = Boolean(minutesGeneration.minutes) || parseSummaryContent(summaryData) != null;
    if (
      hasSummary
      && !autoSwitchedSummaryMeetingIdsRef.current.has(meeting.id)
      && !manuallySelectedTabMeetingIdsRef.current.has(meeting.id)
    ) {
      autoSwitchedSummaryMeetingIdsRef.current.add(meeting.id);
      setActiveTab('summary');
    }
  }, [meeting.id, minutesGeneration.minutes, summaryData]);

  // 停止录音后自动生成纪要：每个会议只触发一次
  useEffect(() => {
    if (!shouldAutoGenerate || !minutesLoaded || minutes !== null || minutesStatus !== 'idle') return;
    if ((meeting.transcripts?.length ?? 0) === 0) return;
    if (autoGeneratedMeetingIdsRef.current.has(meeting.id)) return;
    autoGeneratedMeetingIdsRef.current.add(meeting.id);
    onAutoGenerateComplete?.();
    void generateMinutes();
  }, [
    shouldAutoGenerate,
    minutesLoaded,
    minutes,
    minutesStatus,
    meeting.id,
    meeting.transcripts,
    generateMinutes,
    onAutoGenerateComplete,
  ]);

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.3, ease: 'easeOut' }}
      className="flex flex-col h-screen min-w-0 bg-gray-50"
    >
      <div className="flex flex-1 min-w-0 overflow-hidden">
        <MeetingDetailsSplitView
          activeTab={activeTab}
          onTabChange={(tab) => {
            manuallySelectedTabMeetingIdsRef.current.add(meeting.id);
            setActiveTab(tab);
          }}
          transcript={
            <TranscriptPanel
              transcripts={meetingData.transcripts}
              customPrompt={customPrompt}
              onPromptChange={setCustomPrompt}
              onCopyTranscript={copyOperations.handleCopyTranscript}
              onOpenMeetingFolder={meetingOperations.handleOpenMeetingFolder}
              isRecording={isRecording}
              disableAutoScroll={true}
              usePagination={true}
              segments={segments}
              hasMore={hasMore}
              isLoadingMore={isLoadingMore}
              totalCount={totalCount}
              loadedCount={loadedCount}
              onLoadMore={onLoadMore}
              meetingId={meeting.id}
              meetingFolderPath={meeting.folder_path}
              onRefetchTranscripts={onRefetchTranscripts}
            />
          }
          minutes={
            <MinutesPanel
              meetingId={meeting.id}
              status={minutesGeneration.status}
              progress={minutesGeneration.progress}
              minutes={minutesGeneration.minutes}
              error={minutesGeneration.error}
              legacySummary={meetingData.aiSummary}
              onGenerate={minutesGeneration.generate}
              onCancel={() => {
                minutesGeneration.cancel().catch(() => toast.error('取消纪要生成失败'));
              }}
            />
          }
          quality={<QualityPanel quality={minutesGeneration.quality} />}
        />
      </div>
    </motion.div>
  );
}
